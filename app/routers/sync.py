"""
Offline invoice synchronization API.

Frontend:

    IndexedDB
        |
        v
    POST /api/sync/invoices
        |
        +-- existing client_uuid -> duplicate
        |
        +-- new client_uuid
                |
                v
          validate invoice
                |
                v
          restore product photo
                |
                v
          create Invoice
                |
                v
          create InvoiceItem[]
                |
                v
          generate PDF
                |
                v
          WhatsApp / SMS

Offline photo format:

    photo_base64
    photo_content_type

The client_uuid is the idempotency key.
"""

